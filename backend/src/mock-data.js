export function getMockPlatforms(platformIds = []) {
  if (!platformIds.length) {
    return mockPlatforms;
  }

  return mockPlatforms.filter((platform) => platformIds.includes(platform.id));
}

export function getMockGames({
  startDate,
  endDate,
  platformIds = [],
  minHype = 0,
  withRating = false,
}) {
  return mockGames.filter((game) => {
    const inRange = game.date >= startDate && game.date <= endDate;
    const inPlatform = !platformIds.length || platformIds.includes(game.platform.id);
    const inHype = game.hypes >= minHype;
    const hasRating = !withRating || game.total_rating > 0;

    return inRange && inPlatform && inHype && hasRating;
  });
}
