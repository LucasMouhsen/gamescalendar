function buildGame({
  id,
  name,
  summary,
  storyline,
  cover,
  website,
  genres,
  modes,
  developer,
  publisher,
  rating,
  hypes,
  date,
  platform,
}) {
  return {
    id,
    name,
    summary,
    storyline,
    cover: cover ? { url: cover } : null,
    artworks: [],
    videos: [],
    websites: website ? [{ url: website }] : [],
    genres: genres.map((entry, index) => ({ id: id * 10 + index, name: entry })),
    game_modes: modes.map((entry, index) => ({ id: id * 100 + index, name: entry })),
    developer: developer ? [{ id: id * 1000 + 1, name: developer }] : [],
    publisher: publisher ? [{ id: id * 1000 + 2, name: publisher }] : [],
    total_rating: rating,
    hypes,
    date: mockDate(date),
    platform,
  };
}

